'use strict';

const assert = require('assert');
const fs = require('fs');
const vm = require('vm');
const path = require('path');
let crisp = true;
const context = { shouldUseCrispMaskEdges: () => crisp, LAYER_UI_CONFIG: { paint: { clippable: true, clipBase: true }, sparkles: { clippable: true }, filter: {} } };
vm.createContext(context);
vm.runInContext(fs.readFileSync(path.join(__dirname, '../../js/paint/clip-mask.js'), 'utf8') + '\nglobalThis.api = { getClipBase, getClippedLayers, isClipBodyEntry, getClipContentKey, getClipInsertion };', context);
const { getClipBase, getClippedLayers, isClipBodyEntry, getClipContentKey, getClipInsertion } = context.api;
const base = { id: 'base', type: 'paint' };
const first = { id: 'first', type: 'paint', clipped: true };
const second = { id: 'second', type: 'sparkles', clipped: true };
const layers = [base, first, second];
assert.strictEqual(getClipBase(layers, first), base);
assert.strictEqual(getClipBase(layers, second), base);
assert.deepStrictEqual(Array.from(getClippedLayers(layers, base)), [first, second]);
assert.strictEqual(getClipBase([first], first), null);
assert.strictEqual(getClipBase([{ type: 'filter' }, first], first), null);
assert.strictEqual(getClipBase([{ ...base, isPreview: true }, first], first), null);
assert.strictEqual(getClipBase([base, { ...first, isPreview: true }], { ...first, isPreview: true }), null);
assert.strictEqual(getClipBase([base, { ...first, clipped: false }], first), null);
for (const role of ['fill', 'border', 'stroke', 'background', 'bevel']) assert(isClipBodyEntry({ role }));
for (const role of ['shadow', 'sparkles']) assert(!isClipBodyEntry({ role }));
assert.strictEqual(getClipInsertion(layers, { type: 'paint' }, 1).clipped, true);
assert.strictEqual(getClipInsertion(layers, { type: 'filter' }, 1).index, 3);
const editor = { originalCanvas: { width: 100, height: 80 }, layerManager: { serializeLayer: value => ({ ...value }) } };
const key = getClipContentKey(editor, base);
assert.strictEqual(getClipContentKey(editor, { ...base, opacity: 30, animations: [{ type: 'bounce' }] }), key);
assert.notStrictEqual(getClipContentKey(editor, { ...base, transform: { position: { x: 10, y: 20 } } }), key);
crisp = false;
assert.notStrictEqual(getClipContentKey(editor, base), key);
crisp = true;
editor.originalCanvas.width++;
assert.notStrictEqual(getClipContentKey(editor, base), key);
process.stdout.write('PASS clipping bases, body roles, cache keys and stack insertion\n');
