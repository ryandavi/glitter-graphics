'use strict';

const assert = require('assert');
const fs = require('fs');
const vm = require('vm');
const path = require('path');
const context = vm.createContext({ CONFIG: { canvas: { limits: { maxWidth: 1024, maxHeight: 1024 }, defaults: { blankDocument: { color: '#ffffff' } } } } });
for (const file of ['js/core/canvas.js', 'js/systems/CanvasBounds.js', 'js/transforms/transform-gestures.js']) vm.runInContext(fs.readFileSync(path.resolve(__dirname, '../..', file), 'utf8'), context);
vm.runInContext('globalThis.Bounds = CanvasBounds', context);
const plain = (value) => JSON.parse(JSON.stringify(value));
let artwork = { minX: -10, minY: 20, width: 120, height: 90 };
const editor = { originalCanvas: { width: 400, height: 300 }, layers: [], documentSize: {}, layerManager: { getSelectedLayers: () => ['selected'] }, getArtworkBounds: (layers) => layers ? { minX: 30, minY: 40, width: 60, height: 70 } : artwork, resizeCanvas: (...args) => { editor.applied = args; } };
let syncs = 0;
const bounds = new context.Bounds(editor, () => syncs++);
editor.documentSize.bounds = bounds;
assert.deepStrictEqual(plain(bounds.rect), { x: 0, y: 0, width: 400, height: 300 });
for (const [fx, fy] of [[0, 0], [0.5, 0.5], [1, 1]]) {
	bounds.setRect({ x: 0, y: 0, width: 400, height: 300 });
	bounds.setSize(200, 100, { fx, fy });
	assert.deepStrictEqual(plain(bounds.rect), { x: 200 * fx, y: 200 * fy, width: 200, height: 100 });
}
bounds.setSource('artwork'); bounds.setPadding(5);
assert.deepStrictEqual(plain(bounds.rect), { x: -15, y: 15, width: 130, height: 100 });
artwork.width = 150;
assert(bounds.validate().ok);
assert.strictEqual(bounds.rect.width, 160, 'fitted bounds stayed stale');
bounds.setSource('selection');
assert.deepStrictEqual(plain(bounds.rect), { x: 25, y: 35, width: 70, height: 80 });
bounds.setRatio({ w: 2, h: 1 });
assert.deepStrictEqual(plain([bounds.source, bounds.rect]), ['selection', { x: -20, y: 35, width: 160, height: 80 }], 'a ratio cropped a fitted source or dropped it');
bounds.swapOrientation();
assert.deepStrictEqual(plain([bounds.source, bounds.rect]), ['selection', { x: 25, y: 5, width: 70, height: 140 }]);
bounds.setSource('artwork');
assert.deepStrictEqual(plain(bounds.ratio), { w: 1, h: 2 }, 'changing the fit dropped the ratio');
bounds.setRatio(null);
assert.deepStrictEqual(plain(bounds.rect), { x: -15, y: 15, width: 160, height: 100 });
bounds.setSource('selection'); bounds.setRatio({ w: 2, h: 1 }); bounds.swapOrientation();
bounds.setRect({ x: 1.4, y: -2.6, width: 1025, height: 20 });
assert(!bounds.validate().ok); assert(!bounds.apply().ok); assert(!editor.applied);
bounds.setRect({ x: 10.4, y: -20.6, width: 200.4, height: 100.4 });
bounds.setExtension({ mode: 'color', color: '#123456' });
assert(bounds.apply().ok);
assert.deepStrictEqual(plain(editor.applied), [200, 100, -10, 21, { extensionColor: '#123456', historyLabel: 'Resize canvas' }]);
assert.strictEqual(editor.documentSize.bounds, null);
assert(syncs > 0);
const steps = new context.Bounds(editor);
const start = plain(steps.rect);
assert(!steps.canUndo && !steps.canRedo);
steps.setRect(start);
assert(!steps.canUndo, 'an edit that changes nothing became a step');
steps.beginStep();
steps.setRect({ x: 5, y: 5, width: 100, height: 100 }); steps.setRect({ x: 9, y: 9, width: 100, height: 100 });
steps.endStep();
assert.strictEqual(steps.undoStack.length, 1, 'a drag is one step');
steps.setRect({ x: 10, y: 9, width: 100, height: 100 }, 'nudge'); steps.setRect({ x: 11, y: 9, width: 100, height: 100 }, 'nudge');
assert.strictEqual(steps.undoStack.length, 2, 'a run of nudges is one step');
steps.setRatio({ w: 2, h: 1 });
assert.strictEqual(steps.undoStack.length, 3, 'a ratio pick is one step');
steps.undo();
assert.deepStrictEqual(plain([steps.rect, steps.ratio]), [{ x: 11, y: 9, width: 100, height: 100 }, null]);
steps.undo();
assert.deepStrictEqual(plain(steps.rect), { x: 9, y: 9, width: 100, height: 100 });
steps.undo();
assert.deepStrictEqual(plain(steps.rect), start);
steps.undo();
assert(!steps.canUndo && steps.redoStack.length === 3, 'undo ran past the first step');
steps.redo(); steps.redo();
assert.deepStrictEqual(plain(steps.rect), { x: 11, y: 9, width: 100, height: 100 });
steps.beginStep(); steps.setRect({ x: 50, y: 50, width: 10, height: 10 }); steps.cancelStep();
assert.deepStrictEqual(plain(steps.rect), { x: 11, y: 9, width: 100, height: 100 }, 'a cancelled drag kept its change');
assert(steps.canRedo, 'a cancelled drag dropped the redo steps');
steps.setRect({ x: 0, y: 0, width: 20, height: 20 });
assert(!steps.canRedo, 'a new edit kept the redo steps');
const solve = (...args) => plain(context.resizeRectFromHandle(...args));
const rect = { x: 10, y: 20, width: 100, height: 80 };
assert.deepStrictEqual(solve(rect, 'corner-br', { x: 150, y: 130 }), { x: 10, y: 20, width: 140, height: 110 });
assert.deepStrictEqual(solve(rect, 'edge-left', { x: -20, y: 60 }), { x: -20, y: 20, width: 130, height: 80 });
assert.deepStrictEqual(solve(rect, 'edge-right', { x: 150, y: 60 }, { ratio: { w: 2, h: 1 } }), { x: 10, y: 25, width: 140, height: 70 });
assert.deepStrictEqual(solve(rect, 'corner-br', { x: 150, y: 130 }, { fromCenter: true }), { x: -30, y: -10, width: 180, height: 140 });
assert.deepStrictEqual(solve(rect, 'corner-tl', { x: 500, y: 500 }), { x: 109, y: 99, width: 1, height: 1 });
const proportional = solve(rect, 'corner-br', { x: 149.7, y: 100.2 }, { ratio: { w: 2, h: 1 } });
assert(Math.abs(proportional.width / proportional.height - 2) < 0.02);
console.log('PASS canvas bounds sources, model synchronization, limits, apply, anchors, ratio and handle geometry');
