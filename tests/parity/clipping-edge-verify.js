'use strict';

const assert = require('assert');
const { openApp } = require('../lib/app');
const { exportSnapshot } = require('./export-harness');

async function main() {
	const { browser, page, errors } = await openApp({ document: { width: 180, height: 140 } });
	try {
		const result = await page.evaluate(async () => {
			await editor.loadBlankImage(180, 140, '#ffffff'); editor.animationTicker.setPaused(true);
			const base = editor.shapeGlitterManager.createLayer({ shapeId: 'circle', width: 70, height: 70, position: { x: 90, y: 70 } });
			base.shapeData.fill.mode = 'solid'; base.shapeData.fill.color = '#3366ff'; editor.layerManager.insertLayer(base);
			const content = editor.shapeGlitterManager.createLayer({ shapeId: 'square', width: 130, height: 110, position: { x: 90, y: 70 } });
			content.shapeData.fill.mode = 'solid'; content.shapeData.fill.color = '#ff3366'; editor.layerManager.insertLayer(content);
			editor.saveState('Clipping edge fixture'); window.edgeBaseId = base.id; window.edgeContentId = content.id;
			const history = editor.historyManager.historyIndex; editor.toggleClippingMask([content]);
			const singleStep = editor.historyManager.historyIndex === history + 1;
			await editor.getClipBodyCache().get(base); editor.requestPreviewUpdate();
			const cached = editor.getClipBodyCache().peek(base); content.transform.position.x += 4;
			const ownDragRetainsMask = await editor.getClipBodyCache().get(base) === cached;
			content.transform.position.x -= 4;
			const visual = getLayerCanvasBox(editor, content, { visual: true });
			const clippedBounds = visual.right - visual.left <= 72 && visual.bottom - visual.top <= 72;
			const hiddenPoint = editor.layerManager.getTopVisibleLayerAtPoint(30, 20, { includeBase: false });
			const visiblePoint = editor.layerManager.getTopVisibleLayerAtPoint(90, 70, { includeBase: false });
			const picking = hiddenPoint?.id !== content.id && visiblePoint?.id === content.id;
			base.opacity = 40;
			const composed = await editor.sceneCompositor.composeFrameAt(editor.getSceneSnapshotParams(editor.layers));
			const center = [...composed.imageData.data.slice((70 * 180 + 90) * 4, (70 * 180 + 90) * 4 + 4)];
			base.visible = false;
			const context = await editor.sceneCompositor.prepareContext(editor.getSceneSnapshotParams(editor.layers));
			const hiddenOmitted = !context.layerPlans.some(entry => entry.layer === content) && !context.proceduralSources.some(source => source.ownerLayerId === content.id);
			base.visible = true; base.opacity = 100;
			await editor.undo(); const undoClip = !editor.layerManager.getLayerById(content.id).clipped;
			await editor.redo(); const redoClip = editor.layerManager.getLayerById(content.id).clipped;
			editor.toggleClippingMask([editor.layerManager.getLayerById(content.id)]); await editor.undo(); const undoRelease = editor.layerManager.getLayerById(content.id).clipped;
			editor.layerManager.deleteLayer(base.id); const deleteReleases = !editor.layerManager.getLayerById(content.id).clipped;
			await editor.undo(); const undoDelete = editor.layerManager.getLayerById(content.id).clipped && !!editor.layerManager.getLayerById(base.id);
			return { singleStep, ownDragRetainsMask, clippedBounds, picking, center, hiddenOmitted, undoClip, redoClip, undoRelease, deleteReleases, undoDelete };
		});
		for (const [key, value] of Object.entries(result)) if (key !== 'center') assert(value, key);
		assert(result.center[0] > 130 && result.center[1] > 90 && result.center[3] === 255, `Inherited opacity: ${result.center}`);
		process.stdout.write('PASS clipping picking/bounds, inherited opacity/visibility, mask retention, one-step clip/release/delete undo/redo\n');
		const stack = await page.evaluate(async () => {
			const manager = editor.layerManager, base = manager.getLayerById(window.edgeBaseId), content = manager.getLayerById(window.edgeContentId);
			const project = await editor.projectSerializer.serialize();
			const restored = await manager.deserializeLayer(project.layers.find(layer => layer.id === content.id));
			const duplicate = manager.cloneLayer(content.id, { skipSelection: true, skipHistory: true });
			const persists = restored.clipped && duplicate.clipped && getClipBase(editor.layers, duplicate)?.id === base.id;
			manager.deleteLayer(duplicate.id); editor.saveState('Before reorder');
			manager.draggedLayerId = content.id; manager.dropTargetId = base.id; manager.dropInsertAbove = false;
			manager.handleLayerDrop({ preventDefault() {} });
			const released = !getClipBase(editor.layers, content);
			await editor.undo(); const restoredClip = manager.getLayerById(content.id).clipped && getClipBase(editor.layers, manager.getLayerById(content.id))?.id === base.id;
			await editor.redo(); const redoReorder = !getClipBase(editor.layers, manager.getLayerById(content.id));
			await editor.undo();
			await new Promise(resolve => requestAnimationFrame(() => requestAnimationFrame(resolve)));
			const currentBase = manager.getLayerById(base.id), currentContent = manager.getLayerById(content.id);
			manager.setSelection([base.id, content.id], { activeLayerId: content.id });
			const old = [currentBase.transform.position.x, currentContent.transform.position.x];
			editor.groupTransformManager.translateByCanvasDelta(7, 5, { saveState: true });
			const group = currentBase.transform.position.x === old[0] + 7 && currentContent.transform.position.x === old[1] + 7;
			if (!group) throw new Error(JSON.stringify({ old, after: [currentBase.transform.position.x, currentContent.transform.position.x], selected: manager.getSelectedLayers().map(l => [l.id, l.locked]), entries: editor.groupTransformManager.getLayerEntries().length }));
			const svg = SvgExporter.count(editor.layers).clipped === 1 && !SvgExporter.isEligible(currentContent, editor.layers);
			const filter = editor.filterLayerManager.createLayer({ filterData: { type: 'pixelate', size: 5 } }); manager.insertLayer(filter);
			const signature = editor.filterLayerManager.getInputSignature(filter, editor.filterLayerManager.getSnapshotLayers(filter));
			currentContent.clipped = false;
			const changed = signature !== editor.filterLayerManager.getInputSignature(filter, editor.filterLayerManager.getSnapshotLayers(filter));
			currentContent.clipped = true;
			const filtered = await editor.sceneCompositor.composeFrameAt(editor.getSceneSnapshotParams(editor.layers));
			const outside = [...filtered.imageData.data.slice((20 * 180 + 30) * 4, (20 * 180 + 30) * 4 + 4)];
			return { persists, released, restoredClip, redoReorder, group, svg, changed, snapshot: outside.every(value => value === 255) };
		});
		assert(Object.values(stack).every(Boolean), JSON.stringify(stack));
		process.stdout.write('PASS project/duplicate clipping, reorder undo/redo, joint base/content movement, SVG omission and tier-3 input/output\n');
		const groupRegion = await page.evaluate(async () => {
			await editor.loadBlankImage(180, 140, '#ffffff');
			const shape = editor.shapeGlitterManager.createLayer({ shapeId: 'square', width: 40, height: 40 }); editor.layerManager.insertLayer(shape);
			const filter = editor.filterLayerManager.createLayer({ filterData: { type: 'invert' } }); filter.locked = false; editor.layerManager.insertLayer(filter);
			await new Promise(resolve => requestAnimationFrame(() => requestAnimationFrame(resolve)));
			editor.layerManager.setSelection([shape.id, filter.id], { activeLayerId: filter.id });
			const transform = editor.filterLayerManager.layerTransforms.get(filter.id);
			transform.createTransformHandles();
			const singleHandles = !transform.chrome.element.querySelector('[data-handle-type="rotation"], [data-handle-type="anchor"]');
			transform.updateTransform({ rotation: 30, flipX: true }); const ignoresRotation = filter.transform.rotation === 0 && !filter.transform.flipX;
			editor.groupTransformManager.createTransformHandles();
			const groupHandles = !editor.groupTransformManager.chrome.element.querySelector('[data-handle-type="rotation"]');
			editor.groupTransformManager.translateByCanvasDelta(8, 6, { saveState: true });
			const materialized = filter.filterData.region?.width === 180 && filter.transform.position.x === 98 && filter.transform.position.y === 76;
			await editor.undo(); const undo = editor.layerManager.getLayerById(filter.id).filterData.region === null;
			await editor.redo(); const redo = editor.layerManager.getLayerById(filter.id).filterData.region?.width === 180;
			return { singleHandles, ignoresRotation, groupHandles, materialized, undo, redo };
		});
		assert(Object.values(groupRegion).every(Boolean), JSON.stringify(groupRegion));
		process.stdout.write('PASS filter single/group rotation restrictions and committed group region movement undo/redo\n');
		const loaded = await page.evaluate(async () => {
			await editor.loadBlankImage(180, 140, '#ffffff');
			const base = editor.shapeGlitterManager.createLayer({ shapeId: 'circle', width: 60, height: 60 }); editor.layerManager.insertLayer(base);
			const content = editor.shapeGlitterManager.createLayer({ shapeId: 'square', width: 100, height: 90 }); content.clipped = true; editor.layerManager.insertLayer(content);
			const filter = editor.filterLayerManager.createLayer({ filterData: { type: 'invert', region: { width: 80, height: 70 } } }); filter.transform.position = { x: 65, y: 55 }; editor.layerManager.insertLayer(filter);
			const project = await editor.projectSerializer.serialize();
			editor.isSaved = true;
			await editor.projectSerializer.load(project);
			const restoredFilter = editor.layerManager.getLayerById(filter.id), restoredContent = editor.layerManager.getLayerById(content.id);
			return restoredFilter.filterData.region.width === 80 && restoredFilter.filterData.region.height === 70 && restoredFilter.transform.position.x === 65 && restoredFilter.transform.position.y === 55 && restoredContent.clipped && getClipBase(editor.layers, restoredContent)?.id === base.id;
		});
		assert(loaded, 'Saved project load restores clipping and regional geometry');
		process.stdout.write('PASS full ProjectSerializer save/load restores clipping and regional filter geometry\n');
		const empty = await page.evaluate(async () => {
			await editor.loadBlankImage(180, 140, '#ffffff');
			const base = editor.glitterManager.createLayer(); editor.layerManager.insertLayer(base);
			const layer = editor.shapeGlitterManager.createLayer({ shapeId: 'square', width: 90, height: 80 }); layer.clipped = true; editor.layerManager.insertLayer(layer);
			const body = await editor.getClipBodyCache().get(base);
			const output = await editor.sceneCompositor.composeFrameAt(editor.getSceneSnapshotParams(editor.layers));
			return { alpha: body.getContext('2d').getImageData(90, 70, 1, 1).data[3], pixel: [...output.imageData.data.slice((70 * 180 + 90) * 4, (70 * 180 + 90) * 4 + 4)], row: document.querySelector(`[data-layer-id="${layer.id}"].layer-item`).classList.contains('is-clipped') };
		});
		assert.deepStrictEqual(empty, { alpha: 0, pixel: [255, 255, 255, 255], row: true });
		process.stdout.write('PASS empty fill base clips everything out and retains its Layers mark\n');
		const outline = await page.evaluate(async () => {
			await editor.loadBlankImage(180, 140, '#ffffff');
			const base = editor.shapeGlitterManager.createLayer({ shapeId: 'circle', width: 65, height: 63 });
			base.shapeData.fill.mode = 'none'; base.shapeData.border = { ...getSlotDefaults(LayerType.SHAPE, 'border'), mode: 'solid', widthPx: 7, edgeStyle: 'round' }; editor.layerManager.insertLayer(base);
			PREFERENCES.set('crispMaskEdges', false); const soft = await editor.getClipBodyCache().get(base);
			const alpha = soft.getContext('2d').getImageData(0, 0, 180, 140).data.filter((value, index) => index % 4 === 3);
			PREFERENCES.set('crispMaskEdges', true); const crisp = await editor.getClipBodyCache().get(base);
			return { fractional: alpha.some(value => value > 0 && value < 255), emptyCenter: soft.getContext('2d').getImageData(90, 70, 1, 1).data[3] === 0, invalidated: crisp !== soft };
		});
		assert(Object.values(outline).every(Boolean), JSON.stringify(outline));
		process.stdout.write('PASS Smooth outline body preserves fractional coverage and edge-preference changes invalidate its mask\n');
		const regional = await page.evaluate(async () => {
			await editor.loadBlankImage(180, 140, '#ffffff');
			const filter = editor.filterLayerManager.createLayer({ filterData: { type: 'invert' } }); editor.layerManager.insertLayer(filter); editor.saveState('Whole filter');
			const lockedEditable = filter.locked && canEditLayerInStack(filter) && !isLayerFullyLocked(filter);
			filter.locked = false; editor.filterLayerManager.renderLayer(filter);
			editor.filterLayerManager.updateTransform(filter.id, { position: { x: 60.2, y: 50.4 }, scale: { x: 50, y: 50 } }); editor.saveState('Filter region');
			const region = structuredClone(filter.filterData.region), position = structuredClone(filter.transform.position);
			const under = editor.shapeGlitterManager.createLayer({ shapeId: 'square', width: 20, height: 20, position: { x: 80, y: 60 } }); editor.layerManager.insertLayer(under);
			const stack = editor.layerManager.layers; stack.splice(stack.indexOf(under), 1); stack.splice(stack.indexOf(filter), 0, under);
			const top = (x, y) => editor.layerManager.getTopVisibleLayerAtPoint(x, y, { includeBase: false })?.id;
			const boxPick = top(15, 50) === filter.id && top(40, 40) === filter.id && top(80, 60) === under.id && top(150, 120) === undefined;
			filter.locked = true; const lockedPasses = top(15, 50) === undefined && top(40, 40) === undefined; filter.locked = false;
			editor.layerManager.deleteLayer(under.id, { skipHistory: true, silent: true }); editor.layerManager.setActiveLayer(filter.id);
			await editor.undo(); const undo = editor.layerManager.getLayerById(filter.id).filterData.region === null;
			await editor.redo(); const redo = JSON.stringify(editor.layerManager.getLayerById(filter.id).filterData.region) === JSON.stringify(region);
			const current = editor.layerManager.getLayerById(filter.id);
			const project = await editor.projectSerializer.serialize();
			const restored = await editor.layerManager.deserializeLayer(project.layers.find(layer => layer.id === current.id));
			const duplicate = editor.layerManager.cloneLayer(current.id, { skipSelection: true, skipHistory: true });
			const persisted = JSON.stringify(restored.filterData.region) === JSON.stringify(region) && JSON.stringify(duplicate.filterData.region) === JSON.stringify(region);
			editor.layerManager.deleteLayer(duplicate.id);
			const clone = await editor.layerManager.deserializeLayer(editor.layerManager.serializeLayer(current));
			scaleDocumentLayerState(clone, 2, 3, 2);
			const scaled = clone.filterData.region;
			editor.resizeCanvas(200, 160, 10, 20, { saveHistory: false }); const moved = structuredClone(current.transform.position);
			editor.filterLayerManager.resetTransform(current.id); editor.resizeCanvas(240, 180, 10, 10, { saveHistory: false });
			return { persisted, lockedEditable, region, position, boxPick, lockedPasses, undo, redo, scaled, moved, follows: current.filterData.region === null && current.transform.position.x === 120 && current.transform.position.y === 90 };
		});
		assert.deepStrictEqual(regional.region, { width: 90, height: 70 }); assert.deepStrictEqual(regional.scaled, { width: 180, height: 210 });
		assert.deepStrictEqual(regional.position, { x: 60, y: 50 }); assert.deepStrictEqual(regional.moved, { x: 70, y: 70 });
		for (const key of ['persisted', 'lockedEditable', 'boxPick', 'lockedPasses', 'undo', 'redo', 'follows']) assert(regional[key], key);
		process.stdout.write('PASS filter region rounding, unlocked edge and uncovered-interior picking, undo/redo, document scale, Crop offset and whole-canvas following\n');
		await page.evaluate(async () => {
			await editor.loadBlankImage(180, 140, '#ffffff');
			const base = editor.shapeGlitterManager.createLayer({ shapeId: 'circle', width: 90, height: 80 }); editor.layerManager.insertLayer(base);
			base.animations = [GlitterAnimation.normalizeAnimation({ type: 'bounce', periodMs: 400 })];
			const asset = editor.stickerLibrary.content.find(item => item.isAnimated); await editor.stickerLibrary.ensureAssetDetails(asset.id);
			const content = editor.stickerManager.createLayer(asset.id); content.clipped = true; editor.layerManager.insertLayer(content);
			const filter = editor.filterLayerManager.createLayer({ filterData: { type: 'invert', region: { width: 80, height: 70 } } }); editor.layerManager.insertLayer(filter);
			await editor.ensureHtmlSceneExporter();
			if (editor.htmlSceneExporter.getVisibleStickers().some(layer => layer.id === content.id) || !editor.htmlSceneExporter.getOmissionReason().includes('clipping is unsupported')) throw new Error('HTML clipping omission');
		});
		const gif = await exportSnapshot(page, { baseImage: true, transparency: true, maxFrames: 12 }, { minLayers: 3 });
		assert(gif.bytes.length > 100);
		const mp4 = await page.evaluate(async () => {
			if (!await Mp4Exporter.isSupported()) return null;
			const settings = { ...editor.exportSettings, transparency: false, mp4LengthMode: 'loops', mp4LoopCount: 2, mp4Quality: 'standard' };
			const job = await editor.sceneCompositor.planAnimation({ ...editor.getSceneSnapshotParams(editor.layers), exportSettings: settings, outputFormat: 'mp4', schedule: true, target: EXPORT_TARGETS['animation:mp4'] });
			const blob = await editor.mp4Exporter._encode({ schedulePlan: job.plan, renderScheduleEntry: job.renderScheduleEntry }, settings, { onProgress: () => {}, onStatus: () => {}, onComplete: () => {} });
			const url = URL.createObjectURL(blob), video = document.createElement('video'); video.src = url; video.muted = true;
			await new Promise((resolve, reject) => { video.onloadeddata = resolve; video.onerror = () => reject(new Error('Clipped MP4 decode failed')); });
			const result = { size: blob.size, type: blob.type, width: video.videoWidth, height: video.videoHeight, duration: video.duration, expected: job.plan.totalDuration * 2 / 1000 };
			URL.revokeObjectURL(url); return result;
		});
		if (mp4) { assert(mp4.size > 100 && mp4.type === 'video/mp4' && mp4.width === 180 && mp4.height === 140); assert(Math.abs(mp4.duration - mp4.expected) < 0.05, JSON.stringify(mp4)); process.stdout.write('PASS transparent clipped GIF and decoded two-loop MP4 with Bounce, animated sticker and regional filter\n'); }
		else process.stdout.write('SKIP clipped MP4: H.264 encoder unavailable\n');
		assert.deepStrictEqual(errors, []);
	} finally { await browser.close(); }
}

main().catch(error => { console.error(error); process.exitCode = 1; });
